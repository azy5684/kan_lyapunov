function boundary = origin_contour(x,y,V,c,R)
    contours=contourc(x,y,V,[c c]);
    k=1; boundary=[];
    grid_tol=2*max(x(2)-x(1),y(2)-y(1));
    while k<size(contours,2)
        n=contours(2,k);
        pts=contours(:,k+1:k+n);
        closed=norm(pts(:,1)-pts(:,end))<1e-8;
        if closed && inpolygon(0,0,pts(1,:),pts(2,:)) && all(hypot(pts(1,:),pts(2,:))<=R+grid_tol)
            assert(isempty(boundary),'Multiple contours surrounding the origin.');
            boundary=pts;
        end
        k=k+n+1;
    end
    assert(~isempty(boundary),'No closed origin contour found inside the verification disk.');
end

function [c_star,theta_star,point] = compute_c_circle(Vfun,R)
    previous=NaN;
    for n=[8192,16384]
        step=2*pi/n;
        theta=(0:n-1)*step;
        values=Vfun(R*cos(theta),R*sin(theta));
        assert(all(isfinite(values)), 'Nonfinite value on circle.');
        [best,k]=min(values); best_theta=theta(k);
        candidates=find(values<=circshift(values,1) & values<=circshift(values,-1));
        opts=optimset('TolX',1e-12,'Display','off');
        for j=candidates(:)'
            [t,v]=fminbnd(@(t) Vfun(R*cos(t),R*sin(t)),theta(j)-step,theta(j)+step,opts);
            if v<best
                best=v; best_theta=t;
            end
        end
        if isfinite(previous)
            assert(abs(best-previous)<=1e-9*max(1,abs(best)), 'Boundary minimum did not converge.');
        end
        previous=best;
    end
    c_star=best; theta_star=mod(best_theta,2*pi);
    point=R*[cos(theta_star),sin(theta_star)];
end

function V = model_value(x1,x2,index)
    [v1,v2]=lyapunov_values(x1,x2);
    if index==1, V=v1; else, V=v2; end
end

function [V1,V2] = lyapunov_values(X1,X2)
R2 = X1.^2 + X2.^2;

A = -0.97663326440108067 ...
    + 0.061937637678540769 .* X1 ...
    + 0.083136767305744264 .* X2 ...
    + 0.066182799985678206 .* X1.^2 ...
    - 0.0063102124254070541 .* X1.^3 ...
    + 0.030356809900302671 .* X2.^2 ...
    - 0.00033378373507509637 .* X2.^3;

B = -0.1514466014176501 ...
    + 0.22616137253517146 .* X1 ...
    + 0.24892716840878146 .* X2 ...
    + 0.028352137392954172 .* X1.^2 ...
    - 0.023981279481698578 .* X1.^3 ...
    + 0.00033376550667786598 .* X2.^2 ...
    - 0.007878437491729855 .* X2.^3;

C = -0.25966982519065229 ...
    + 0.32505283138169921 .* A ...
    - 0.39268049243178976 .* B ...
    - 0.34874856170476282 .* A.^2 ...
    + 0.23206701434448451 .* A.^3 ...
    + 0.57221233348079814 .* B.^2 ...
    + 0.013415205774900419 .* B.^3;

D = -0.13990804814139696 ...
    + 0.34077051858892332 .* A ...
    - 0.060130878049973933 .* B ...
    - 0.12054204463729022 .* A.^2 ...
    + 0.090115335242599168 .* A.^3 ...
    + 0.26619248584968319 .* B.^2 ...
    + 0.1104131628547755 .* B.^3;

V1 = R2 .* ( ...
      0.15905734122715842 ...
    - 0.24245020837828921 .* C ...
    - 0.14362991967304309 .* D ...
    - 0.32947365832755793 .* C.^2 ...
    - 0.85578443609039467 .* C.^3 ...
    - 0.29147418693376664 .* D.^2 ...
    - 0.28671493821440325 .* D.^3 );

S1 = softplus_stable(-0.29756572842597961 ...
    + 16.415559768676758 .* X1 ...
    + 0.70501166582107544 .* X2);

S2 = softplus_stable(0.88649141788482666 ...
    + 0.27399942278862 .* X1 ...
    - 0.0033397874794900417 .* X2);

S3 = softplus_stable(0.10695143789052963 ...
    - 0.52939772605895996 .* X1 ...
    + 1.1625970602035522 .* X2 ...
    + 2.7547850608825684 .* S1 ...
    - 0.0013194747734814882 .* S2);

S4 = softplus_stable(2.9648308753967285 ...
    + 2.3879997730255127 .* X1 ...
    - 3.3717305660247803 .* X2 ...
    + 9.0540552139282227 .* S1 ...
    + 0.81064271926879883 .* S2);

V2 = R2 .* softplus_stable( ...
    -0.62595003843307495 ...
    + 0.23087705671787262 .* X1 ...
    - 0.00091802823590114713 .* X2 ...
    - 0.0058394242078065872 .* S3 ...
    - 0.0066630993969738483 .* S4);

end

function y = softplus_stable(x)
    y = max(x,0) + log1p(exp(-abs(x)));
end

function [f1, f2] = f_grid(x1, x2)
    f1 = (-1.14045842 .* x1 ...
        - 0.22802382 .* x2 ...
        + 0.70931150 .* x1 .* (x2.^2) ...
        + 0.49013606 .* sin(x1) ...
        - 0.93472954 .* (x1.^2) .* x2);

    f2 = (-0.22802382 .* x1 ...
        - 1.31777801 .* x2 ...
        + 0.51827385 .* (x1.^2) .* x2 ...
        - 0.69488369 .* sin(x2));
end
